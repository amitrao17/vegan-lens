// Regenerates rules/rulesData.js (the bundled copy content scripts load synchronously) from rules/rules.json.
// Data only: the output is a single JSON literal assigned to a global. Run after editing rules.json: node tools/build-rules.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'rules');
const json = JSON.stringify(JSON.parse(fs.readFileSync(path.join(dir, 'rules.json'), 'utf8')));
fs.writeFileSync(path.join(dir, 'rulesData.js'), '// GENERATED by tools/build-rules.js from rules/rules.json. Do not edit.\nself.VeganRulesBundled = ' + json + ';\n');
